#!/usr/bin/env python3
"""Single source of truth for the RV328 pad ring.

Generates, from the table below:
  rtl/rv328_chip_top.v            pad instances + core + analog macro
  flow/librelane/slot_1x0p5.yaml  pad order for the wafer.space half-height slot
  flow/librelane/slot_1x1.yaml    the same pads on the full-height slot
  docs/bondout.md                 die pad -> package pin table

Sides are listed in increasing coordinate order (south/north: left to right,
east/west: bottom to top), with package pin 1 at the top of the west side and
pins counting counter-clockwise, as on a TQFP-32.
"""
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

# ATmega328PB 32-pin TQFP/QFN pinout: pin -> (name, alternate functions)
PINS = {
    1: ("PD3", "INT1 / OC2B"), 2: ("PD4", "T0 / XCK0"), 3: ("PE0", "ACO / SDA1 / ICP4"),
    4: ("VCC", ""), 5: ("GND", ""), 6: ("PE1", "T4 / SCL1"),
    7: ("PB6", "XTAL1 / TOSC1"), 8: ("PB7", "XTAL2 / TOSC2"),
    9: ("PD5", "OC0B / T1"), 10: ("PD6", "OC0A / AIN0"), 11: ("PD7", "AIN1"),
    12: ("PB0", "ICP1 / CLKO"), 13: ("PB1", "OC1A"), 14: ("PB2", "SS0 / OC1B"),
    15: ("PB3", "MOSI0 / TXD1 / OC2A"), 16: ("PB4", "MISO0 / RXD1"),
    17: ("PB5", "SCK0 / XCK1"), 18: ("AVCC", ""), 19: ("PE2", "ADC6 / ICP3 / SS1"),
    20: ("AREF", ""), 21: ("GND", ""), 22: ("PE3", "ADC7 / T3 / MOSI1"),
    23: ("PC0", "ADC0 / MISO1"), 24: ("PC1", "ADC1 / SCK1"), 25: ("PC2", "ADC2"),
    26: ("PC3", "ADC3"), 27: ("PC4", "ADC4 / SDA0"), 28: ("PC5", "ADC5 / SCL0"),
    29: ("PC6", "RESET"), 30: ("PD0", "RXD0 / OC3A"), 31: ("PD1", "TXD0 / OC4A"),
    32: ("PD2", "INT0 / OC3B / OC4B"),
}
PIN_OF = {v[0]: k for k, v in PINS.items() if v[0] not in ("VCC", "GND")}

# Pad kinds: G = GPIO (bidirectional), A = analog tap, F* = serial memory,
# J* = JTAG test pad, S = spare, power pads by template name.
def G(n): return ("G", n)
def A(n, pin): return ("A", n, pin)
PWR = lambda n: ("P", n)

WEST = [PWR("vss_pads[0]"), PWR("vdd_pads[0]"),
        A("XTAL2", "PB7"), G("PB7"), A("XTAL1", "PB6"), G("PB6"), G("PE1"), G("PE0"), G("PD4"), G("PD3"),
        PWR("dvss_pads[6]"), PWR("dvdd_pads[6]")]
SOUTH = [G("PD5"), G("PD6"), A("AIN0", "PD6"), G("PD7"),
         PWR("dvss_pads[0]"), PWR("dvdd_pads[0]"),
         A("AIN1", "PD7"), G("PB0"), G("PB1"), G("PB2"), G("PB3"), G("PB4"),
         ("F", "FL_CSN"), ("F", "FL_SCK"), ("F", "FL_MOSI"), ("F", "FL_MISO"),
         ("J", "TCK"), ("J", "TMS"),
         PWR("dvss_pads[1]"), PWR("dvdd_pads[1]"),
         ("J", "TDI"), ("J", "TDO"), ("S", 0), ("S", 1)]
EAST = [PWR("dvss_pads[2]"), PWR("dvdd_pads[2]"),
        G("PB5"), A("AVCC", "AVCC"), G("PE2"), A("ADC6", "PE2"), A("AREF", "AREF"), G("PE3"), A("ADC7", "PE3"),
        ("S", 2),
        PWR("dvss_pads[3]"), PWR("dvdd_pads[3]")]
NORTH = [G("PD2"), G("PD1"), G("PD0"), G("PC6"),
         PWR("dvss_pads[5]"), PWR("dvdd_pads[5]"),
         G("PC5"), A("ADC5", "PC5"), G("PC4"), A("ADC4", "PC4"), G("PC3"), A("ADC3", "PC3"),
         G("PC2"), A("ADC2", "PC2"), ("S", 3), ("S", 4), ("S", 5), ("S", 6),
         PWR("dvss_pads[4]"), PWR("dvdd_pads[4]"),
         G("PC1"), A("ADC1", "PC1"), G("PC0"), A("ADC0", "PC0")]
SIDES = [("SOUTH", SOUTH), ("EAST", EAST), ("NORTH", NORTH), ("WEST", WEST)]

PORT_BASE = {"B": 0, "C": 8, "D": 16, "E": 24}
CLOCK_INPUTS = {6}          # PB6 (XTAL1 / external clock): no input buffer beside the pad


def inst(p):
    k = p[0]
    if k == "P":
        return p[1].replace("[", "\\\\[").replace("]", "\\\\]") + ".pad"
    if k == "G": return "pad_" + p[1].lower()
    if k == "A": return "apad_" + p[1].lower()
    if k in "FJ": return "pad_" + p[1].lower()
    if k == "S": return "pad_spare%d" % p[1]


def bond(p):
    k = p[0]
    if k == "P":
        return "GND (pins 5, 21, exposed pad)" if "vss" in p[1] else "VCC (pin 4)"
    if k == "G": return "pin %d (%s)" % (PIN_OF[p[1]], p[1])
    if k == "A":
        if p[1] in ("AVCC", "AREF"): return "pin %d (%s)" % (PIN_OF[p[1]], p[1])
        return "pin %d (%s), second wire" % (PIN_OF[p[2]], p[2])
    if k == "F": return "serial-memory die " + p[1][3:]
    if k == "J": return "not bonded (JTAG test pad)"
    return "not bonded"


SLOTS = {   # name: (file, title, die area, core area)
    "SLOT_1X0P5": ("slot_1x0p5.yaml", "half-height slot (1x0.5)", [0, 0, 3932, 2531], [442, 442, 3490, 2089]),
    "SLOT_1X1":   ("slot_1x1.yaml", "full-height slot (1x1)", [0, 0, 3932, 5122], [442, 442, 3490, 4680]),
}


def gen_yaml():
    # the same 72 pads in both slots; on the full-height slot the east and west pads are spread over the longer sides
    for define, (fname, title, die, core) in SLOTS.items():
        out = ["# Generated by scripts/gen_padring.py - do not edit by hand.",
               "# wafer.space GF180MCU %s, 72 pads." % title,
               "FP_SIZING: absolute", "DIE_AREA: %s" % die,
               "CORE_AREA: %s" % core, "",
               'VERILOG_DEFINES: ["%s", "RV328_TECH_GF180", "RV328_ANALOG_STUB", "RV328_WAFERSPACE_IDS", "RV328_SC9T"]' % define, ""]
        for name, pads in SIDES:
            out.append("PAD_%s: [" % name)
            out += ['    "%s",' % inst(p) for p in pads]
            out[-1] = out[-1].rstrip(",")
            out.append("]\n")
        open(os.path.join(ROOT, "flow/librelane", fname), "w").write("\n".join(out))


def gen_bondout():
    out = ["# RV328 bond-out", "",
           "Generated by `scripts/gen_padring.py`. Die pads are listed per side in increasing",
           "coordinate order (south and north: left to right; east and west: bottom to top).",
           "Package pin 1 is at the top of the west side; pins count counter-clockwise.", ""]
    n = 0
    for name, pads in SIDES:
        out += ["## %s side" % name.capitalize(), "", "| # | Pad instance | Cell | Bond to |", "|---|---|---|---|"]
        for p in pads:
            cell = {"P": "dvdd/dvss", "G": "bi_24t", "A": "asig_5p0", "F": "bi_24t / in_c",
                    "J": "in_s / in_c / bi_24t", "S": "in_c (pull-down)"}[p[0]]
            if p[0] == "P": cell = "dvss" if "vss" in p[1] else "dvdd"
            out.append("| %d | `%s` | %s | %s |" % (n, inst(p).replace("\\\\", ""), cell, bond(p)))
            n += 1
        out.append("")
    out += ["## Package pins", "", "| Pin | Name | Alternate functions | Die pads |", "|---|---|---|---|"]
    allp = [p for _, s in SIDES for p in s]
    for pin in range(1, 33):
        nm, alt = PINS[pin]
        if nm == "VCC": pads = "all `dvdd`/`vdd` pads"
        elif nm == "GND": pads = "all `dvss`/`vss` pads"
        else:
            pads = ", ".join("`%s`" % inst(p) for p in allp
                             if (p[0] == "G" and p[1] == nm) or (p[0] == "A" and (p[2] == nm)))
        out.append("| %d | %s | %s | %s |" % (pin, nm, alt, pads))
    open(os.path.join(ROOT, "docs/bondout.md"), "w").write("\n".join(out) + "\n")


def gen_top():
    allp = [p for _, s in SIDES for p in s]
    pw = "\n`ifdef USE_POWER_PINS\n\t\t.DVDD (DVDD), .DVSS (DVSS), .VDD (VDD), .VSS (VSS),\n`endif\n\t\t"
    body = []
    for p in allp:
        k = p[0]
        if k == "G":
            port, bit = p[1][1], int(p[1][2])
            idx = PORT_BASE[port] + bit
            # Schmitt-trigger input on RESET and the external clock pin
            cs = "1'b1" if p[1] in ("PC6", "PB6") else "1'b0"
            body.append(
                "\t(* keep *) gf180mcu_fd_io__bi_24t %s (%s.PAD (P%s[%d]), .A (pad_out[%d]), .OE (pad_oe[%d]), "
                ".Y (pad_in[%d]),\n\t\t.IE (pad_ie[%d]), .PU (pad_pu[%d]), .PD (1'b0), .CS (%s), .SL (1'b1));"
                % (inst(p), pw, port, bit, idx, idx, idx, idx, idx, cs))
        elif k == "A":
            body.append("\t(* keep *) gf180mcu_fd_io__asig_5p0 %s (%s.ASIG5V (A_%s));" % (inst(p), pw, p[1]))
        elif k == "F" or (k == "J" and p[1] == "TDO"):
            sig = {"FL_CSN": "p_fl_csn", "FL_SCK": "p_fl_sck", "FL_MOSI": "p_fl_mosi", "TDO": "jtag_tdo"}.get(p[1])
            if sig:
                body.append(
                    "\t(* keep *) gf180mcu_fd_io__bi_24t %s (%s.PAD (%s), .A (%s), .OE (1'b1), .Y (),\n"
                    "\t\t.IE (1'b0), .PU (1'b0), .PD (1'b0), .CS (1'b0), .SL (1'b0));" % (inst(p), pw, p[1], sig))
            else:
                body.append("\t(* keep *) gf180mcu_fd_io__in_c %s (%s.PAD (FL_MISO), .Y (p_fl_miso), .PU (1'b1), .PD (1'b0));"
                            % (inst(p), pw))
        elif k == "J":
            cell, pu, pd = ("in_s", "1'b0", "1'b1") if p[1] == "TCK" else ("in_c", "1'b1", "1'b0")
            body.append("\t(* keep *) gf180mcu_fd_io__%s %s (%s.PAD (%s), .Y (jtag_%s), .PU (%s), .PD (%s));"
                        % (cell, inst(p), pw, p[1], p[1].lower(), pu, pd))
        elif k == "S":
            body.append("\t(* keep *) gf180mcu_fd_io__in_c %s (%s.PAD (SPARE[%d]), .Y (), .PU (1'b0), .PD (1'b1));"
                        % (inst(p), pw, p[1]))
    # buffers beside the pads (RV328_PADBUF): instance u_pb_<signal>_<index>, placed by the floorplan
    used, bufs = set(), []
    for p in allp:
        if p[0] == "G":
            idx = PORT_BASE[p[1][1]] + int(p[1][2])
            used.add(idx)
            for tag, src, dst in (("a", "c_out", "pad_out"), ("e", "c_oe", "pad_oe"), ("u", "c_pu", "pad_pu"), ("i", "c_ie", "pad_ie")):
                bufs.append("\trv328_padbuf u_pb_%s_%d (.i (%s[%d]), .o (%s[%d]));" % (tag, idx, src, idx, dst, idx))
            if idx in CLOCK_INPUTS:
                # the clock pin goes to the clock tree as it leaves the pad: a buffer here would put the
                # external clock one buffer behind the copy the oscillator stand-in takes from the same pad
                bufs.append("\tassign c_in[%d] = pad_in[%d];" % (idx, idx))
            else:
                bufs.append("\trv328_padbuf u_pb_y_%d (.i (pad_in[%d]), .o (c_in[%d]));" % (idx, idx, idx))
    for idx in range(32):
        if idx not in used:
            bufs.append("\tassign c_in[%d] = pad_in[%d];" % (idx, idx))
    for name in ("csn", "sck", "mosi"):
        bufs.append("\trv328_padbuf u_pb_fl_%s (.i (core_fl_%s), .o (p_fl_%s));" % (name, name, name))
    bufs.append("\trv328_padbuf u_pb_fl_miso (.i (p_fl_miso), .o (core_fl_miso));")
    tmpl = open(os.path.join(ROOT, "scripts/chip_top.v.in")).read()
    open(os.path.join(ROOT, "rtl/rv328_chip_top.v"), "w").write(tmpl.replace("@PADS@", "\n".join(body)).replace("@PADBUFS@", "\n".join(bufs)))


def pad_info():
    """Pad instance -> package pin and function, for the layout viewer."""
    info = {}
    for side, pads in SIDES:
        for p in pads:
            name = inst(p).replace("\\\\", "")
            k = p[0]
            d = {"side": side.lower(), "bond": bond(p)}
            if k == "P":
                gnd = "vss" in p[1]
                d.update(kind="power", label="GND" if gnd else "VCC", pin=(5 if gnd else 4),
                         fn="ground" if gnd else "supply, 5 V pad ring and core")
            elif k == "G":
                d.update(kind="gpio", label=p[1], pin=PIN_OF[p[1]], fn=PINS[PIN_OF[p[1]]][1])
            elif k == "A":
                d.update(kind="analog", label=p[1] + " (analog)", pin=PIN_OF[p[2]],
                         fn="analog tap, second bond wire on the same lead" if p[1] not in ("AVCC", "AREF") else "analog pin",
                         note="Not connected in the digital-first build.")
            elif k == "F":
                d.update(kind="test", label=p[1], fn="serial memory die inside the package")
            elif k == "J":
                d.update(kind="test", label=p[1], fn="JTAG test pad, not bonded in the 32-pin package")
            else:
                d.update(kind="test", label="spare", fn="unused, tied off")
            info[name] = d
    pins = [{"pin": n, "name": PINS[n][0], "fn": PINS[n][1]} for n in range(1, 33)]
    return {"pads": info, "pins": pins}


if __name__ == "__main__":
    for name, pads in SIDES:
        assert len(pads) == (24 if name in ("SOUTH", "NORTH") else 12), name
    gen_yaml(); gen_bondout(); gen_top()
    if len(sys.argv) > 1:
        json.dump(pad_info(), open(sys.argv[1], "w"), indent=1)
    print("pads:", sum(len(s) for _, s in SIDES))
